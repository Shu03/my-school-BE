function buildCatalog() {
    const constants = loadConstants();
    const models = loadPrismaModels();
    const moduleDirs = fs
        .readdirSync(abs("src/modules"), { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .map((d) => d.name)
        .sort();

    /** @type {Record<string, string>} module dir -> service name */
    const moduleToService = {};
    for (const dir of moduleDirs) moduleToService[dir] = dir;
    for (const [group, dirs] of Object.entries(config.serviceGroups)) {
        for (const dir of dirs) moduleToService[dir] = group;
    }
    const serviceNames = [...new Set(Object.values(moduleToService))].sort();

    /** @type {Record<string, any>} */
    const services = {};
    for (const name of serviceNames) {
        const dirs = moduleDirs.filter((d) => moduleToService[d] === name);
        const files = dirs
            .flatMap((d) => walk(`src/modules/${d}`))
            .filter((f) => f.endsWith(".ts"));
        const prodFiles = files.filter((f) => !f.endsWith(".spec.ts"));
        const specFiles = files.filter((f) => f.endsWith(".spec.ts"));
        const extraTests = walk("test").filter(
            (f) =>
                /\.(e2e|int)-spec\.ts$/.test(f) && dirs.some((d) => path.basename(f).startsWith(d)),
        );

        /** @type {Record<string, { kind: string, symbols: Set<string>, via: Set<string>, calls: Set<string> }>} */
        const deps = {};
        for (const file of prodFiles) {
            /** @type {Map<string, string>} imported symbol -> target service */
            const symbolTarget = new Map();
            for (const imp of parseModuleImports(file)) {
                const target = moduleToService[imp.target];
                if (!target || target === name) continue;
                deps[target] ??= {
                    kind: "type",
                    symbols: new Set(),
                    via: new Set(),
                    calls: new Set(),
                };
                const d = deps[target];
                imp.symbols.forEach((s) => {
                    d.symbols.add(s);
                    symbolTarget.set(s, target);
                });
                d.via.add(path.basename(file));
                const runtime =
                    !imp.typeOnly &&
                    (file.endsWith(".module.ts") ||
                        imp.symbols.some((s) => /(Service|Module)$/.test(s)));
                if (runtime) d.kind = "runtime";
            }
            for (const [type, methods] of injectedCalls(file)) {
                const target = symbolTarget.get(type);
                if (!target) continue;
                for (const m of methods) deps[target].calls.add(`${type}.${m}`);
            }
        }

        const src = prodFiles.map((f) => read(f)).join("\n");
        const usage = prismaUsage(src, models);
        const serviceFiles = prodFiles.filter((f) => f.endsWith(".service.ts"));
        const schemaFiles = [
            ...new Set([...usage.reads, ...usage.writes].map((m) => models[m])),
        ].sort();

        services[name] = {
            name,
            agent: `svc-${name}`,
            infra: config.infraServices.includes(name),
            modules: dirs,
            paths: dirs.map((d) => `src/modules/${d}/`),
            publicApi: dirs.flatMap((d) => parseBarrelExports(`src/modules/${d}/index.ts`)),
            routes: prodFiles
                .filter((f) => f.endsWith(".controller.ts"))
                .flatMap((f) => parseControllers(f, constants)),
            prisma: {
                reads: usage.reads,
                writes: usage.writes,
                schemaFiles,
            },
            dependsOn: Object.entries(deps)
                .sort(([a], [b]) => a.localeCompare(b))
                .map(([target, d]) => ({
                    service: target,
                    agent: `svc-${target}`,
                    kind: d.kind,
                    symbols: [...d.symbols].sort(),
                    calls: [...d.calls].sort(),
                    via: [...d.via].sort(),
                })),
            usedBy: [],
            errors: errorInventory(prodFiles),
            tests: {
                unit: specFiles.map(testStats),
                other: extraTests.map(testStats),
            },
            serviceFiles,
            serviceLoc: serviceFiles.reduce((n, f) => n + read(f).split("\n").length, 0),
            sourceHash: sourceHash([...prodFiles, ...schemaFiles]),
            notesFile: `.agents/services/${name}.notes.md`,
        };
    }

    for (const svc of Object.values(services)) {
        for (const dep of svc.dependsOn) {
            services[dep.service].usedBy.push({
                service: svc.name,
                agent: svc.agent,
                kind: dep.kind,
                symbols: dep.symbols,
                calls: dep.calls,
            });
        }
    }

    // src/common also consumes module contracts (guards, decorators) — record it as a consumer.
    /** @type {Record<string, Set<string>>} */
    const commonUses = {};
    for (const file of walk("src/common").filter((f) => f.endsWith(".ts"))) {
        for (const imp of parseModuleImports(file)) {
            const target = moduleToService[imp.target];
            if (!target) continue;
            commonUses[target] ??= new Set();
            imp.symbols.forEach((s) => commonUses[target].add(s));
        }
    }
    for (const [target, symbols] of Object.entries(commonUses)) {
        services[target].usedBy.push({
            service: "src/common",
            agent: null,
            kind: "type",
            symbols: [...symbols].sort(),
            calls: [],
        });
    }

    return {
        $comment: `${GENERATED_MARKER} — do not edit. Run \`pnpm agents:build\`.`,
        apiPrefix: "/api/v1",
        services,
    };
}


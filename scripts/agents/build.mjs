/** @param {string} text */
function parseSpec(text) {
    const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!m) throw new Error("spec is missing frontmatter");
    /** @type {Record<string, string>} */
    const meta = {};
    for (const line of m[1].split("\n")) {
        const kv = line.match(/^(\w[\w-]*):\s*(.*)$/);
        if (kv) meta[kv[1]] = kv[2].trim();
    }
    for (const key of ["name", "description", "tier", "access"]) {
        if (!meta[key]) throw new Error(`spec is missing '${key}'`);
    }
    return { meta, body: m[2].trim() + "\n" };
}

/** @param {{ name: string, description: string, tier: string, access: string, body: string, source: string }} a */
function renderClaude(a) {
    const tier = config.modelTiers[a.tier];
    const access = config.access[a.access];
    if (!tier || !access) throw new Error(`${a.name}: unknown tier/access`);
    return [
        "---",
        `name: ${a.name}`,
        `description: ${JSON.stringify(a.description)}`,
        `tools: ${access.claudeTools}`,
        `model: ${tier.claude}`,
        "---",
        "",
        `<!-- ${GENERATED_MARKER} from ${a.source} — do not edit; run \`pnpm agents:build\`. -->`,
        "",
        a.body.trim(),
        "",
    ].join("\n");
}

/** @param {string} s */
function tomlBasic(s) {
    return JSON.stringify(s);
}

/** @param {string} s Multi-line basic string; escapes backslashes and triple quotes. */
function tomlMultiline(s) {
    const escaped = s.replace(/\\/g, "\\\\").replace(/"""/g, '""\\"');
    return `"""\n${escaped}"""`;
}

/** @param {{ name: string, description: string, tier: string, access: string, body: string, source: string }} a */
function renderCodex(a) {
    const tier = config.modelTiers[a.tier];
    const access = config.access[a.access];
    return [
        `# ${GENERATED_MARKER} from ${a.source} — do not edit; run \`pnpm agents:build\`.`,
        `name = ${tomlBasic(a.name)}`,
        `description = ${tomlBasic(a.description)}`,
        `model = ${tomlBasic(tier.codex.model)}`,
        `model_reasoning_effort = ${tomlBasic(tier.codex.reasoning)}`,
        `sandbox_mode = ${tomlBasic(access.codexSandbox)}`,
        `developer_instructions = ${tomlMultiline(a.body.trim() + "\n")}`,
        "",
    ].join("\n");
}

/** @param {string} s */
const cell = (s) => String(s).replace(/\|/g, "\\|");

/** @param {any} svc */
function renderRoutes(svc) {
    if (svc.routes.length === 0) return "_No HTTP routes._";
    const showPerms = svc.routes.some((/** @type {any} */ r) => r.permissions.length > 0);
    const rows = svc.routes.map((/** @type {any} */ r) => {
        const roles = r.public
            ? "**PUBLIC**"
            : r.roles.length
              ? r.roles.join(", ")
              : "any authenticated";
        const perms = showPerms ? ` ${r.permissions.join(", ") || "—"} |` : "";
        const flags = r.throttled ? " (custom throttle)" : "";
        return `| ${r.method} | \`${r.path}\` | \`${r.handler}\` | ${roles} |${perms} ${cell(r.summary)}${flags} |`;
    });
    return [
        `| Method | Path | Handler | Roles |${showPerms ? " Permissions |" : ""} Summary |`,
        `|---|---|---|---|${showPerms ? "---|" : ""}---|`,
        ...rows,
    ].join("\n");
}

/** @param {any[]} links @param {Record<string, any>} services */
function renderLinks(links, services) {
    if (links.length === 0) return "- _None._";
    return links
        .map((l) => {
            const who = l.agent ? `**${l.agent}**` : `\`${l.service}\``;
            const infra = l.agent && services[l.service]?.infra ? " (infra)" : "";
            const kind =
                l.kind === "runtime" ? "runtime (module/service injection)" : "type/contract only";
            const symbols = l.symbols.map((/** @type {string} */ s) => `\`${s}\``).join(", ");
            const calls = l.calls?.length
                ? `. Methods called: ${l.calls.map((/** @type {string} */ c) => `\`${c}()\``).join(", ")}`
                : "";
            return `- ${who}${infra}: ${kind}. Symbols: ${symbols}${calls}`;
        })
        .join("\n");
}

/** @param {any} svc */
function renderFacts(svc) {
    const unitCases = svc.tests.unit.reduce(
        (/** @type {number} */ n, /** @type {any} */ t) => n + t.cases,
        0,
    );
    const allStub =
        svc.tests.unit.length > 0 && svc.tests.unit.every((/** @type {any} */ t) => t.stubOnly);
    const testLine =
        svc.tests.unit.length === 0
            ? "**none**. No spec files exist."
            : `${svc.tests.unit.length} spec file(s), ${unitCases} case(s)${allStub ? '. **Stub-only ("should be defined")**, so real coverage is effectively zero' : ""}`;
    const other = svc.tests.other.length
        ? svc.tests.other.map((/** @type {any} */ t) => `\`${t.file}\``).join(", ")
        : "none";
    const throws = Object.entries(svc.errors.throws)
        .map(([t, n]) => `${t}×${n}`)
        .join(", ");
    const list = (/** @type {string[]} */ xs) =>
        xs.length ? xs.map((x) => `\`${x}\``).join(", ") : "none";
    return [
        `- Paths: ${list(svc.paths)}`,
        `- Service files: ${list(svc.serviceFiles)} (${svc.serviceLoc} lines total)`,
        `- Public API (\`index.ts\`): ${svc.publicApi.length ? list(svc.publicApi) : "_none_"}`,
        `- Prisma models written: ${svc.prisma.writes.length ? svc.prisma.writes.join(", ") : "none"}`,
        `- Prisma models read only: ${svc.prisma.reads.length ? svc.prisma.reads.join(", ") : "none"}`,
        `- Schema files: ${list(svc.prisma.schemaFiles)}`,
        `- Exceptions thrown directly: ${throws || "none"}`,
        `- \`ERROR_*\` constants used: ${list(svc.errors.errorConstants)}`,
        `- Unit tests: ${testLine}`,
        `- Integration/E2E tests: ${other}`,
        `- Source hash: \`${svc.sourceHash}\` (module source + schema files it touches)`,
    ].join("\n");
}

/** @param {any} svc @returns {"fresh" | "stale" | "unstamped" | "missing"} */
function notesState(svc) {
    if (!exists(svc.notesFile)) return "missing";
    const stamped = stampedHash(read(svc.notesFile));
    if (!stamped) return "unstamped";
    return stamped === svc.sourceHash ? "fresh" : "stale";
}

/** @param {any} svc */
function staleBanner(svc) {
    const state = notesState(svc);
    if (state === "fresh" || state === "missing") return "";
    const why =
        state === "stale"
            ? `the module's code or schema changed after these notes were last verified (notes \`${stampedHash(read(svc.notesFile))}\` vs code \`${svc.sourceHash}\`)`
            : "these notes have never been verified against the current code";
    return (
        `> ⚠ **Module knowledge may be stale.** Cause: ${why}. Treat every claim below as a hypothesis, ` +
        `verify it against the code before relying on it, then update the notes and run ` +
        `\`pnpm agents:stamp ${svc.name}\`.\n\n`
    );
}

/** @param {any} svc @param {Record<string, any>} services @param {string} template */
function renderServiceAgent(svc, services, template) {
    const notesPath = svc.notesFile;
    const notesRaw = exists(notesPath)
        ? read(notesPath)
              .replace(/<!--[\s\S]*?-->\s*/g, "")
              .trim()
        : `_No notes yet. Create \`${notesPath}\` from the code (Purpose, Business rules & invariants, Access control notes, Cross-module contracts, Known pitfalls / risks, Test focus), then run \`pnpm agents:stamp ${svc.name}\`._`;
    const notes = staleBanner(svc) + notesRaw.replace(/^## /gm, "### ");
    const purpose = exists(notesPath) ? purposeOf(read(notesPath)) : "";
    const values = {
        agentName: svc.agent,
        service: svc.name,
        paths: svc.paths.join("`, `"),
        testPattern: svc.modules.map((/** @type {string} */ m) => `src/modules/${m}`).join(" "),
        dependsOn: renderLinks(svc.dependsOn, services),
        usedBy: renderLinks(svc.usedBy, services),
        facts: renderFacts(svc),
        routes: renderRoutes(svc),
        notes,
    };
    const body = template.replace(/\{\{(\w+)\}\}/g, (_, k) => {
        if (!(k in values)) throw new Error(`service template: unknown placeholder ${k}`);
        return values[/** @type {keyof typeof values} */ (k)];
    });
    const downstream = svc.usedBy
        .filter((/** @type {any} */ u) => u.agent)
        .map((/** @type {any} */ u) => u.agent);
    const description =
        `Owner/expert for the ${svc.name} module (${svc.paths.join(", ")}). ${purpose} ` +
        `Use for any feature, bug, question, review or test touching this module` +
        (downstream.length ? `; changes to its contract affect ${downstream.join(", ")}.` : ".");
    return {
        name: svc.agent,
        description: description.replace(/\s+/g, " ").trim(),
        tier: config.serviceAgent.tier,
        access: config.serviceAgent.access,
        body,
        source: `.agents/templates/service-agent.md + ${notesPath}`,
    };
}

/** @param {Record<string, any>} services */
function renderServicesMd(services) {
    const list = Object.values(services);
    const edges = [];
    for (const s of list) {
        if (s.infra) continue;
        for (const d of s.dependsOn) {
            if (services[d.service].infra) continue;
            edges.push(
                `    ${s.name.replace(/-/g, "_")} ${d.kind === "runtime" ? "-->" : "-.->"} ${d.service.replace(/-/g, "_")}`,
            );
        }
    }
    const nodes = list
        .filter((s) => !s.infra)
        .map((s) => `    ${s.name.replace(/-/g, "_")}["${s.name}"]`);
    const rows = list.map((s) => {
        const unit = s.tests.unit.reduce(
            (/** @type {number} */ n, /** @type {any} */ t) => n + t.cases,
            0,
        );
        const stub =
            s.tests.unit.length && s.tests.unit.every((/** @type {any} */ t) => t.stubOnly)
                ? " (stub)"
                : "";
        return `| \`${s.agent}\` | ${s.paths.map((/** @type {string} */ p) => `\`${p}\``).join(" ")} | ${s.routes.length} | ${s.dependsOn.map((/** @type {any} */ d) => d.service).join(", ") || "—"} | ${s.usedBy.map((/** @type {any} */ u) => u.service).join(", ") || "—"} | ${unit}${stub} |`;
    });
    const anyPerms = list.some((s) =>
        s.routes.some((/** @type {any} */ r) => r.permissions.length > 0),
    );
    const routeRows = list.flatMap((s) =>
        s.routes.map(
            (/** @type {any} */ r) =>
                `| ${s.name} | ${r.method} | \`${r.path}\` | ${r.public ? "PUBLIC" : r.roles.join(", ") || "any auth"} |${anyPerms ? ` ${r.permissions.join(", ") || "—"} |` : ""}`,
        ),
    );
    const notesRows = list.map(
        (s) => `| \`${s.agent}\` | \`${s.sourceHash}\` | ${notesState(s)} |`,
    );
    return [
        `<!-- ${GENERATED_MARKER} — do not edit; run \`pnpm agents:build\`. -->`,
        "",
        "# Service Catalog",
        "",
        "Everything here is extracted from `src/` and `prisma/schema/` by the TypeScript compiler API. Nothing comes from documentation.",
        "",
        "Solid arrow = runtime dependency (module import / service injection). Dashed = type/contract only.",
        "`platform` (prisma + health) is infrastructure used by every module and is omitted from the graph.",
        "",
        "```mermaid",
        "graph LR",
        ...nodes,
        ...edges,
        "```",
        "",
        "| Agent | Paths | Routes | Depends on | Used by | Unit test cases |",
        "|---|---|---|---|---|---|",
        ...rows,
        "",
        "## Route & access matrix (prefix `/api/v1`)",
        "",
        "Guards only check roles. Per-record access (class or subject teacher, approved access requests, ownership) is enforced inside the services; see each `svc-*` agent.",
        "",
        `| Service | Method | Path | Roles |${anyPerms ? " Permissions |" : ""}`,
        `|---|---|---|---|${anyPerms ? "---|" : ""}`,
        ...routeRows,
        "",
        "## Knowledge freshness",
        "",
        "`fresh` means the notes were verified against exactly this code. `stale`/`unstamped` means verify against the code, update the notes, then run `pnpm agents:stamp <service>`.",
        "",
        "| Agent | Source hash | Notes |",
        "|---|---|---|",
        ...notesRows,
        "",
    ].join("\n");
}

/** @param {{ name: string, description: string }[]} core @param {Record<string, any>} services */
function renderRoster(core, services) {
    return [
        "<!-- agents:roster:start -->",
        `<!-- ${GENERATED_MARKER} — edit .agents/specs/*.md or .agents/services/*.notes.md instead. -->`,
        "",
        "| Agent | Use it for |",
        "|---|---|",
        ...core.map((a) => `| \`${a.name}\` | ${cell(a.description)} |`),
        "",
        "Per-service owner agents (see `.agents/catalog/SERVICES.md` for the dependency graph):",
        "",
        "| Agent | Module(s) | Depends on | Used by |",
        "|---|---|---|---|",
        ...Object.values(services).map(
            (s) =>
                `| \`${s.agent}\` | ${s.paths.map((/** @type {string} */ p) => `\`${p}\``).join(" ")} | ${s.dependsOn.map((/** @type {any} */ d) => d.agent).join(", ") || "—"} | ${s.usedBy.map((/** @type {any} */ u) => u.agent ?? u.service).join(", ") || "—"} |`,
        ),
        "<!-- agents:roster:end -->",
    ].join("\n");
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
    /** @type {Map<string, string>} repo-relative path -> content */
    const outputs = new Map();

    let catalog = buildCatalog();

    if (STAMP.length) {
        const targets = STAMP.includes("all") ? Object.keys(catalog.services) : STAMP;
        for (const name of targets) {
            const svc = catalog.services[name];
            if (!svc) throw new Error(`--stamp: unknown service '${name}'`);
            if (!exists(svc.notesFile)) throw new Error(`--stamp: ${svc.notesFile} does not exist`);
            const notes = read(svc.notesFile);
            const header = `<!-- source-hash: ${svc.sourceHash} · Hand-maintained module knowledge, derived ONLY from code (src/, prisma/). Embedded into svc-${name} by scripts/agents/build.mjs. After verifying against code, run \`pnpm agents:stamp ${name}\`. -->`;
            const body = notes.replace(/^\s*<!--[\s\S]*?-->\s*/, "");
            fs.writeFileSync(abs(svc.notesFile), `${header}\n\n${body}`);
            console.log(`stamped ${svc.notesFile} @ ${svc.sourceHash}`);
        }
        catalog = buildCatalog();
    }

    outputs.set(".agents/catalog/services.json", JSON.stringify(catalog, null, 4) + "\n");
    outputs.set(".agents/catalog/SERVICES.md", renderServicesMd(catalog.services));

    const core = walk(".agents/specs")
        .filter((f) => f.endsWith(".md"))
        .map((file) => {
            const { meta, body } = parseSpec(read(file));
            if (`${meta.name}.md` !== path.basename(file))
                throw new Error(`${file}: name must match filename`);
            return {
                name: meta.name,
                description: meta.description,
                tier: meta.tier,
                access: meta.access,
                body,
                source: file,
            };
        });

    const template = read(".agents/templates/service-agent.md");
    const svcAgents = Object.values(catalog.services).map((s) =>
        renderServiceAgent(s, catalog.services, template),
    );

    for (const agent of [...core, ...svcAgents]) {
        outputs.set(`.claude/agents/${agent.name}.md`, renderClaude(agent));
        outputs.set(`.codex/agents/${agent.name}.toml`, renderCodex(agent));
    }

    for (const skill of config.skills) {
        const files = walk(`.agents/skills/${skill}`);
        if (files.length === 0)
            throw new Error(
                `skill '${skill}' listed in config but .agents/skills/${skill} is empty`,
            );
        for (const f of files)
            outputs.set(f.replace(/^\.agents\/skills\//, ".claude/skills/"), read(f));
    }

    const agentsMd = read("AGENTS.md");
    const rosterRe = /<!-- agents:roster:start -->[\s\S]*?<!-- agents:roster:end -->/;
    if (!rosterRe.test(agentsMd)) throw new Error("AGENTS.md is missing the agents:roster markers");
    outputs.set("AGENTS.md", agentsMd.replace(rosterRe, renderRoster(core, catalog.services)));

    // Generated files that are no longer produced (e.g. a deleted module) are stale.
    const stale = [...walk(".claude/agents"), ...walk(".codex/agents")].filter(
        (f) => !outputs.has(f) && read(f).includes(GENERATED_MARKER),
    );
    for (const skill of config.skills) {
        for (const f of walk(`.claude/skills/${skill}`)) if (!outputs.has(f)) stale.push(f);
    }

    const changed = [...outputs]
        .filter(([file, content]) => !exists(file) || read(file) !== content)
        .map(([f]) => f);

    const notStamped = Object.values(catalog.services)
        .map((s) => ({ name: s.name, state: notesState(s) }))
        .filter((s) => s.state !== "fresh");
    for (const s of notStamped) {
        console.warn(
            `warning: ${s.name} notes are ${s.state}. Verify them against the code, then run \`pnpm agents:stamp ${s.name}\`.`,
        );
    }
    const failOnNotes = CHECK && config.staleNotes === "fail" && notStamped.length > 0;

    if (CHECK) {
        if (changed.length || stale.length || failOnNotes) {
            console.error(
                "Agent files are out of date. Run `pnpm agents:build` and commit the result.",
            );
            for (const f of changed) console.error(`  changed: ${f}`);
            for (const f of stale) console.error(`  stale:   ${f}`);
            if (failOnNotes)
                console.error("  notes not verified against current code (see warnings)");
            process.exit(1);
        }
        console.log(`Agent files up to date (${outputs.size} files checked).`);
        return;
    }

    for (const f of changed) {
        fs.mkdirSync(path.dirname(abs(f)), { recursive: true });
        fs.writeFileSync(abs(f), /** @type {string} */ (outputs.get(f)));
    }
    for (const f of stale) fs.rmSync(abs(f));
    console.log(
        `Agents built: ${core.length} core + ${svcAgents.length} service agents, ` +
            `${config.skills.length} skills. ${changed.length} file(s) written, ${stale.length} stale removed.`,
    );
}

main();

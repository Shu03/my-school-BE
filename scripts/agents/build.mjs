/**
 * Agent generator for my-school-BE.
 *
 * Source of truth (hand-written):
 *   .agents/agents.config.json        model tiers, access profiles, service groups, skills list
 *   .agents/specs/<agent>.md          core agent definitions (frontmatter + instructions)
 *   .agents/templates/service-agent.md
 *   .agents/services/<svc>.notes.md   hand-maintained module knowledge
 *   .agents/skills/<skill>/           shared skills (Codex reads this location natively)
 *
 * Generated (never edit by hand):
 *   .agents/catalog/services.json     modules, routes, permissions, Prisma models, dependency graph
 *   .agents/catalog/SERVICES.md       human-readable catalog + Mermaid graph
 *   .claude/agents/*.md               Claude Code subagents
 *   .codex/agents/*.toml              Codex custom agents
 *   .claude/skills/<skill>/           mirror of the shared skills for Claude Code
 *   AGENTS.md roster block            between <!-- agents:roster:start/end --> markers
 *
 * Usage:
 *   node scripts/agents/build.mjs                    write all outputs
 *   node scripts/agents/build.mjs --check            exit 1 if any output is stale (CI / pre-commit)
 *   node scripts/agents/build.mjs --stamp <svc|all>  mark notes as verified against the current code
 *
 * Service agents are built from CODE ONLY (TypeScript AST of src/ + prisma/schema). Documentation
 * is never read. Hand-written notes are stamped with a hash of the module source; when the code
 * changes, the generated agent carries a "verify against code" banner until the notes are re-stamped.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const CHECK = process.argv.includes("--check");
const STAMP = (() => {
    const i = process.argv.indexOf("--stamp");
    return i === -1 ? [] : process.argv.slice(i + 1).filter((a) => !a.startsWith("--"));
})();
const GENERATED_MARKER = "GENERATED by scripts/agents/build.mjs";
const HTTP_DECORATORS = new Set(["Get", "Post", "Put", "Patch", "Delete"]);
const PRISMA_OPS =
    "findUnique|findUniqueOrThrow|findFirst|findFirstOrThrow|findMany|create|createMany|createManyAndReturn|update|updateMany|upsert|delete|deleteMany|count|aggregate|groupBy";
const PRISMA_WRITE_OPS = new Set([
    "create",
    "createMany",
    "createManyAndReturn",
    "update",
    "updateMany",
    "upsert",
    "delete",
    "deleteMany",
]);

const rel = (/** @type {string} */ p) => path.relative(ROOT, p).split(path.sep).join("/");
const abs = (/** @type {string} */ p) => path.join(ROOT, p);
const read = (/** @type {string} */ p) => fs.readFileSync(abs(p), "utf8");
const exists = (/** @type {string} */ p) => fs.existsSync(abs(p));

/** @param {string} dir @returns {string[]} repo-relative file paths, sorted */
function walk(dir) {
    if (!exists(dir)) return [];
    /** @type {string[]} */
    const out = [];
    for (const entry of fs.readdirSync(abs(dir), { withFileTypes: true })) {
        const p = `${dir}/${entry.name}`;
        if (entry.isDirectory()) out.push(...walk(p));
        else out.push(p);
    }
    return out.sort();
}


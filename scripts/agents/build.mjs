/** PERMISSION_X -> "X" from app.constants.ts */
function loadConstants() {
    /** @type {Record<string, string>} */
    const map = {};
    const src = read("src/common/constants/app.constants.ts");
    for (const m of src.matchAll(/export const (\w+)\s*=\s*"([^"]*)"/g)) map[m[1]] = m[2];
    return map;
}

/** Model name -> schema file */
function loadPrismaModels() {
    /** @type {Record<string, string>} */
    const models = {};
    for (const file of walk("prisma/schema").filter((f) => f.endsWith(".prisma"))) {
        for (const m of read(file).matchAll(/^model\s+(\w+)\s*\{/gm)) models[m[1]] = file;
    }
    return models;
}

/** @param {string} file */
function parseTs(file) {
    return ts.createSourceFile(file, read(file), ts.ScriptTarget.ES2021, true, ts.ScriptKind.TS);
}

/** @param {ts.Node} node @returns {{ name: string, args: ts.NodeArray<ts.Expression> | [] }[]} */
function decoratorsOf(node) {
    const decs = ts.canHaveDecorators(node) ? (ts.getDecorators(node) ?? []) : [];
    return decs.map((d) => {
        const e = d.expression;
        if (ts.isCallExpression(e)) return { name: e.expression.getText(), args: e.arguments };
        return { name: e.getText(), args: [] };
    });
}

/** @param {ts.Expression | undefined} e */
function stringArg(e) {
    return e && (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) ? e.text : "";
}

/** @param {readonly ts.Expression[]} args @param {Record<string,string>} constants */
function symbolArgs(args, constants) {
    return args.map((a) => {
        const text = a.getText();
        if (constants[text] !== undefined) return constants[text];
        if (ts.isStringLiteral(a)) return a.text;
        return text.includes(".") ? text.split(".").pop() : text;
    });
}

/** @param {ReturnType<typeof decoratorsOf>} decs @param {string} name */
const findDec = (decs, name) => decs.find((d) => d.name === name);

/** @param {string} file @param {Record<string,string>} constants */
function parseControllers(file, constants) {
    const sf = parseTs(file);
    /** @type {any[]} */
    const routes = [];
    sf.forEachChild((node) => {
        if (!ts.isClassDeclaration(node)) return;
        const cdecs = decoratorsOf(node);
        const ctrl = findDec(cdecs, "Controller");
        if (!ctrl) return;
        const base = stringArg(ctrl.args[0]);
        const classRoles = findDec(cdecs, "Roles");
        const classPerms = findDec(cdecs, "Permissions");
        const classPublic = !!findDec(cdecs, "Public");
        for (const member of node.members) {
            if (!ts.isMethodDeclaration(member)) continue;
            const decs = decoratorsOf(member);
            const http = decs.find((d) => HTTP_DECORATORS.has(d.name));
            if (!http) continue;
            const roles = findDec(decs, "Roles") ?? classRoles;
            const perms = findDec(decs, "Permissions") ?? classPerms;
            const op = findDec(decs, "ApiOperation");
            let summary = "";
            if (op && op.args[0] && ts.isObjectLiteralExpression(op.args[0])) {
                for (const prop of op.args[0].properties) {
                    if (ts.isPropertyAssignment(prop) && prop.name.getText() === "summary") {
                        summary = stringArg(prop.initializer);
                    }
                }
            }
            const sub = stringArg(http.args[0]);
            const full = `/${[base, sub].filter(Boolean).join("/")}`.replace(/\/+/g, "/");
            routes.push({
                method: http.name.toUpperCase(),
                path: full,
                handler: member.name.getText(),
                public: classPublic || !!findDec(decs, "Public"),
                roles: roles ? symbolArgs(roles.args, constants) : [],
                permissions: perms ? symbolArgs(perms.args, constants) : [],
                throttled: !!findDec(decs, "Throttle"),
                summary,
                source: `${file}:${sf.getLineAndCharacterOfPosition(member.getStart()).line + 1}`,
            });
        }
    });
    return routes;
}

/** @param {string} file @returns {{ target: string, symbols: string[], typeOnly: boolean }[]} */
function parseModuleImports(file) {
    const sf = parseTs(file);
    /** @type {{ target: string, symbols: string[], typeOnly: boolean }[]} */
    const out = [];
    sf.forEachChild((node) => {
        if (!ts.isImportDeclaration(node)) return;
        const spec = stringArg(/** @type {ts.Expression} */ (node.moduleSpecifier));
        const m = spec.match(/^@modules\/([a-z0-9-]+)/);
        if (!m) return;
        const clause = node.importClause;
        /** @type {string[]} */
        const symbols = [];
        if (clause?.name) symbols.push(clause.name.text);
        if (clause?.namedBindings && ts.isNamedImports(clause.namedBindings)) {
            for (const el of clause.namedBindings.elements) symbols.push(el.name.text);
        }
        out.push({ target: m[1], symbols, typeOnly: !!clause?.isTypeOnly });
    });
    return out;
}

/** @param {string} file */
function parseBarrelExports(file) {
    if (!exists(file)) return [];
    const sf = parseTs(file);
    /** @type {string[]} */
    const names = [];
    sf.forEachChild((node) => {
        if (
            ts.isExportDeclaration(node) &&
            node.exportClause &&
            ts.isNamedExports(node.exportClause)
        ) {
            for (const el of node.exportClause.elements) {
                names.push(
                    node.isTypeOnly || el.isTypeOnly ? `type ${el.name.text}` : el.name.text,
                );
            }
        }
    });
    return names;
}

/** @param {string} src @param {Record<string,string>} models */
function prismaUsage(src, models) {
    const reads = new Set();
    const writes = new Set();
    const re = new RegExp(
        `\\b(?:prismaService|prisma|tx)\\s*\\.\\s*([a-z]\\w*)\\s*\\.\\s*(${PRISMA_OPS})\\b`,
        "g",
    );
    for (const m of src.matchAll(re)) {
        const model = m[1][0].toUpperCase() + m[1].slice(1);
        if (!models[model]) continue;
        (PRISMA_WRITE_OPS.has(m[2]) ? writes : reads).add(model);
    }
    for (const w of writes) reads.delete(w);
    return { reads: [...reads].sort(), writes: [...writes].sort() };
}

/**
 * Methods called on constructor-injected dependencies, e.g. `this.accessPolicy.resolveSubjectAccess(`.
 * @param {string} file
 * @returns {Map<string, Set<string>>} injected type name -> method names
 */
function injectedCalls(file) {
    const sf = parseTs(file);
    /** @type {Map<string, Set<string>>} */
    const calls = new Map();
    sf.forEachChild((node) => {
        if (!ts.isClassDeclaration(node)) return;
        /** @type {Map<string, string>} param name -> type name */
        const params = new Map();
        for (const member of node.members) {
            if (!ts.isConstructorDeclaration(member)) continue;
            for (const p of member.parameters) {
                if (p.type && ts.isTypeReferenceNode(p.type) && ts.isIdentifier(p.name)) {
                    params.set(p.name.text, p.type.typeName.getText());
                }
            }
        }
        if (params.size === 0) return;
        /** @param {ts.Node} n */
        const visit = (n) => {
            if (
                ts.isCallExpression(n) &&
                ts.isPropertyAccessExpression(n.expression) &&
                ts.isPropertyAccessExpression(n.expression.expression) &&
                n.expression.expression.expression.kind === ts.SyntaxKind.ThisKeyword
            ) {
                const type = params.get(n.expression.expression.name.text);
                if (type) {
                    if (!calls.has(type)) calls.set(type, new Set());
                    /** @type {Set<string>} */ (calls.get(type)).add(n.expression.name.text);
                }
            }
            ts.forEachChild(n, visit);
        };
        ts.forEachChild(node, visit);
    });
    return calls;
}

/**
 * Exception types thrown and ERROR_* constants referenced.
 * @param {string[]} files
 */
function errorInventory(files) {
    /** @type {Record<string, number>} */
    const throws = {};
    const constants = new Set();
    for (const file of files) {
        const sf = parseTs(file);
        /** @param {ts.Node} n */
        const visit = (n) => {
            if (
                ts.isThrowStatement(n) &&
                n.expression &&
                ts.isNewExpression(n.expression) &&
                ts.isIdentifier(n.expression.expression)
            ) {
                const type = n.expression.expression.text;
                throws[type] = (throws[type] ?? 0) + 1;
            }
            if (ts.isIdentifier(n) && /^ERROR_[A-Z0-9_]+$/.test(n.text)) constants.add(n.text);
            ts.forEachChild(n, visit);
        };
        visit(sf);
    }
    return {
        throws: Object.fromEntries(Object.entries(throws).sort(([a], [b]) => a.localeCompare(b))),
        errorConstants: [...constants].sort(),
    };
}

/** @param {string[]} files */
function sourceHash(files) {
    const h = crypto.createHash("sha256");
    for (const f of [...files].sort()) {
        h.update(f);
        h.update("\0");
        h.update(read(f).replace(/\r\n/g, "\n"));
        h.update("\0");
    }
    return h.digest("hex").slice(0, 12);
}

/** @param {string} notes @returns {string | null} */
function stampedHash(notes) {
    const m = notes.match(/source-hash:\s*([0-9a-f]{12})/);
    return m ? m[1] : null;
}

/** @param {string} file */
function testStats(file) {
    const src = read(file);
    const cases = [...src.matchAll(/\b(?:it|test)(?:\.each\([^)]*\))?\s*\(\s*["'`]([^"'`]*)/g)].map(
        (m) => m[1],
    );
    return {
        file,
        cases: cases.length,
        stubOnly: cases.length > 0 && cases.every((c) => c === "should be defined"),
    };
}

/** @param {string} notes */
function purposeOf(notes) {
    const m = notes.match(/## Purpose\s*\n([\s\S]*?)(\n## |$)/);
    const text = (m ? m[1] : "").replace(/\s+/g, " ").trim();
    const first = text.split(/(?<=\.)\s/)[0] ?? "";
    return first.replace(/`/g, "");
}

